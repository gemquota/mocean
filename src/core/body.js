import { clamp, mix } from './math.js';

export function createGait() {
  return { phase: 0, amplitude: 0.22, frequency: 1.25, steering: 0, energy: 1, tailVelocity: 0 };
}

/** A travelling lateral wave: small at the head, amplified toward the caudal peduncle. */
export function stepGait(gait, behaviour, speed, turnIntent, dt) {
  const profiles = {
    CRUISE: [0.22, 1.35],
    EXPLORE: [0.28, 1.55],
    TURN: [0.34, 1.7],
    DART: [0.43, 2.55],
    GLIDE: [0.055, 0.55],
    RECOVER: [0.12, 0.9]
  };
  const [baseAmplitude, baseFrequency] = profiles[behaviour] ?? profiles.CRUISE;
  const burstCost = behaviour === 'DART' ? 0.24 * dt : 0;
  gait.energy = clamp(gait.energy - burstCost + (behaviour === 'RECOVER' ? 0.13 : 0.035) * dt, 0.12, 1);
  const reserve = 0.45 + gait.energy * 0.55;
  const targetAmplitude = baseAmplitude * reserve;
  const targetFrequency = baseFrequency * (0.72 + gait.energy * 0.28);
  gait.amplitude = mix(gait.amplitude, targetAmplitude, 1 - Math.exp(-dt * 2.8));
  gait.frequency = mix(gait.frequency, targetFrequency, 1 - Math.exp(-dt * 2.2));
  gait.steering = mix(gait.steering, clamp(turnIntent, -1, 1), 1 - Math.exp(-dt * 3.5));
  gait.phase += dt * gait.frequency * Math.PI * 2;

  const tailLateralSpeed = gait.amplitude * gait.frequency * Math.PI * 2;
  gait.tailVelocity = tailLateralSpeed;
  // Propulsive acceleration is generated by the lateral tail stroke, not a drive slider.
  const thrust = clamp(0.30 * tailLateralSpeed * tailLateralSpeed, 0, behaviour === 'DART' ? 2.0 : 1.15);
  return { thrust, steering: gait.steering };
}

export function deformPoint(point, gait) {
  const u = clamp((0.98 - point.x) / 2.18, 0, 1.35);
  const envelope = u * u;
  const travellingWave = Math.sin(gait.phase - u * 3.0);
  const lateral = gait.amplitude * envelope * travellingWave;
  const turnCurve = gait.steering * 0.16 * envelope;
  return {
    x: point.x,
    y: point.y,
    z: point.z + lateral + turnCurve
  };
}
